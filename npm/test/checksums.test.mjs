import assert from 'node:assert/strict'
import test from 'node:test'
import { expectedChecksum, parseChecksums } from '../src/checksums.mjs'

const HASH_A = 'a'.repeat(64)
const HASH_B = 'b'.repeat(64)

test('parses standard checksum lines', () => {
  const checksums = parseChecksums(
    ['# generated by the release workflow', `${HASH_A}  OpenInOpenCodeSetup.exe`, ''].join('\r\n'),
  )

  assert.equal(checksums.get('OpenInOpenCodeSetup.exe'), HASH_A)
})

test('parses binary markers, uppercase hashes and ./ prefixes', () => {
  const checksums = parseChecksums(
    ['C'.repeat(64) + ' *OpenInOpenCodeSetup.exe', `${HASH_B}  ./OpenInOpenCodeSetup-1.0.0.0.exe`].join(
      '\n',
    ),
  )

  assert.equal(checksums.get('OpenInOpenCodeSetup.exe'), 'c'.repeat(64))
  assert.equal(checksums.get('OpenInOpenCodeSetup-1.0.0.0.exe'), HASH_B)
})

test('ignores a UTF-8 byte order mark', () => {
  const checksums = parseChecksums(`\uFEFF${HASH_A}  OpenInOpenCodeSetup.exe`)
  assert.equal(checksums.get('OpenInOpenCodeSetup.exe'), HASH_A)
})

test('ignores malformed lines', () => {
  const checksums = parseChecksums(
    ['not a hash  file.exe', 'abc  short.exe', `${'g'.repeat(64)}  invalid.exe`, ''].join('\n'),
  )

  assert.equal(checksums.size, 0)
})

test('returns the checksum for the requested asset', () => {
  const text = `${HASH_A}  OpenInOpenCodeSetup.exe\n${HASH_B}  other.exe`
  assert.equal(expectedChecksum(text, 'OpenInOpenCodeSetup.exe'), HASH_A)
})

test('refuses an asset that is missing from checksums.txt', () => {
  assert.throws(
    () => expectedChecksum(`${HASH_A}  other.exe`, 'OpenInOpenCodeSetup.exe'),
    /No SHA-256 entry for OpenInOpenCodeSetup\.exe/,
  )
})
